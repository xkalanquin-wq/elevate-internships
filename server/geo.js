/**
 * The spellings a board might use for one place: "St Paul", "St. Paul" and
 * "Saint Paul"; "Ft. Worth"; "Mt. Laurel"; and the town at the end of
 * "Leland HQ - Lehi" or "Downtown Austin".
 */
function cityVariants(city) {
  const out = new Set([city]);
  const tail = city.split(/\s[-–—:]\s/).pop().trim();
  if (tail) out.add(tail);
  for (const c of [...out]) {
    out.add(c.replace(/^(greater|downtown|metro|central)\s+/, ''));
  }
  for (const c of [...out]) {
    if (/^(st\.?|saint)\s/.test(c)) {
      const rest = c.replace(/^(st\.?|saint)\s+/, '');
      out.add(`saint ${rest}`);
      out.add(`st. ${rest}`);
    }
    out.add(c.replace(/^ft\.?\s+/, 'fort '));
    out.add(c.replace(/^mt\.?\s+/, 'mount '));
  }
  return [...out];
}

/** [lat, lon] for a city in a state, trying each spelling; METROS first. */
function lookupCity(city, state) {
  for (const c of cityVariants(city)) {
    const key = `${c}, ${state}`;
    // METROS is hand-tuned and carries aliases the place tables have no row
    // for, such as "silicon valley, ca".
    const hit = METROS[key] || cityTable().get(key);
    if (hit) return { coords: hit, key };
  }
  return null;
}

