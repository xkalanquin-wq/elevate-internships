/* --- Bundled US geography ---------------------------------------------------
 * Every US ZIP (41,488) and every US city GeoNames lists a postal code for
 * (29,542), generated by scripts/build-geodata.js from the GeoNames export.
 * See server/data/GEONAMES-LICENCE.txt — CC BY 4.0, attribution required.
 *
 * Both tables load on first use rather than at import, so starting the server
 * stays instant for anything that never runs a search. Parsing ~2.3MB of CSV
 * costs well under a second, once.
 *
 * This replaced a hand-maintained table of 62 metros. With 62 entries, most
 * real job locations could not be placed, and unplaceable meant the radius
 * filter did not apply — which is how a 25-mile search returned Bengaluru.
 * -------------------------------------------------------------------------- */

let ZIP_TABLE = null;
let CITY_TABLE = null;

function loadTable(file, onRow) {
  // server/data holds shipped content (the catalog, these tables). The sibling
  // data/ at the project root is runtime state — the database and the geocode
  // cache — and these belong with the content, not the state.
  const full = path.join(here, 'data', file);
  try {
    const text = fs.readFileSync(full, 'utf8');
    let n = 0;
    for (const line of text.split('\n')) {
      if (!line) continue;
      onRow(line);
      n++;
    }
    return n;
  } catch (err) {
    // Missing data files must not take the server down — the app falls back to
    // the network geocoder and the metro table, exactly as it did before.
    console.warn(`[geo] ${file} unavailable (${err.code || err.message}); falling back to the network geocoder.`);
    return 0;
  }
}

function zipTable() {
  if (ZIP_TABLE) return ZIP_TABLE;
  ZIP_TABLE = new Map();
  loadTable('us-zips.csv', (line) => {
    const [zip, lat, lon, city, state] = line.split(',');
    ZIP_TABLE.set(zip, { lat: Number(lat), lon: Number(lon), city, state, zip });
  });
  return ZIP_TABLE;
}

function cityTable() {
  if (CITY_TABLE) return CITY_TABLE;
  CITY_TABLE = new Map();
  const add = (line) => {
    const [city, state, lat, lon] = line.split('|');
    const key = `${city}, ${state}`;
    if (!CITY_TABLE.has(key)) CITY_TABLE.set(key, [Number(lat), Number(lon)]);
  };
  // Postal place names first, then every Census town, township and county
  // (scripts/build-census-places.js) for the places the Post Office files
  // under a neighbour's name.
  loadTable('us-cities.csv', add);
  loadTable('us-places.csv', add);
  return CITY_TABLE;
}

/** ZIP -> { lat, lon, city, state }. Local table first; network only if absent. */
export async function geocodeZip(zip) {
  const key = `zip:${zip}`;
  if (cache[key]) return cache[key];

  // The bundled table answers essentially every real ZIP with no network call,
  // which also means the radius works offline and cannot be broken by
  // Zippopotam being slow or down.
  const local = zipTable().get(String(zip).trim());
  if (local) return local;

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 10_000);
  try {
    const res = await fetch(`https://api.zippopotam.us/us/${zip}`, {
      signal: controller.signal,
      headers: { 'User-Agent': 'career-launchpad/1.0' },
    });
    if (!res.ok) return null;
    const j = await res.json();
    const p = j.places?.[0];
    if (!p) return null;

    const out = {
      lat: Number(p.latitude),
      lon: Number(p.longitude),
      city: p['place name'],
      state: p['state abbreviation'],
      zip,
    };
    cache[key] = out;
    cacheDirty = true;
    return out;
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

/** Great-circle distance in miles. */
export function distanceMiles(a, b) {
  if (!a || !b) return null;
  const R = 3958.8;
  const rad = (d) => (d * Math.PI) / 180;
  const dLat = rad(b.lat - a.lat);
  const dLon = rad(b.lon - a.lon);
  const s =
    Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return Math.round(R * 2 * Math.asin(Math.sqrt(s)));
}

