// Location handling. The app takes a US ZIP code, turns it into coordinates,
// and filters listings by real distance in miles.
//
// Before this existed the radius did nothing: "Bristol, CT" is not a location
// The Muse recognises, so it silently returned remote-only jobs and the radius
// selector was decorative.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const cacheFile = path.join(here, '..', 'data', 'geocache.json');

let cache = {};
try {
  cache = JSON.parse(fs.readFileSync(cacheFile, 'utf8'));
} catch {
  cache = {};
}

let cacheDirty = false;
function persist() {
  if (!cacheDirty) return;
  try {
    fs.mkdirSync(path.dirname(cacheFile), { recursive: true });
    fs.writeFileSync(cacheFile, JSON.stringify(cache));
    cacheDirty = false;
  } catch {
    /* cache is an optimisation; losing it is not fatal */
  }
}
setInterval(persist, 30_000).unref?.();

