/** Normalises a full state name or abbreviation to its two-letter code. */
function toStateCode(raw) {
  // Dots go entirely, so "D.C." is DC as well as "N.Y." is NY.
  const s = String(raw || '').trim().toLowerCase().replace(/\./g, '').replace(/\s+/g, ' ');
  if (STATE_ABBR[s]) return STATE_ABBR[s];
  return US_ABBRS.has(s) ? s : null;
}

